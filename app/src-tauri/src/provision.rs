//! Builds the worker-side install script (models, custom nodes, local-save node) and patches it into the
//! Vast template's on-start script so every new worker has everything it needs.
use base64::Engine;
use flate2::{write::GzEncoder, Compression};
use serde_json::Value;
use std::io::Write;

const LOCAL_NODE: &str = include_str!("../aivs_save_b64.py");
const BEGIN: &str = "# >>> AIVS BEGIN (managed by AI Video Studio, do not edit)";
const END: &str = "# <<< AIVS END";

pub fn build_script(packs: &[Value], include_local_node: bool) -> String {
    let mut s = String::from(
        "#!/bin/bash\n# Generated by AI Video Studio\nC=/workspace/ComfyUI\nM=$C/models\nN=$C/custom_nodes\n\
         PIP=$(ls /venv/*/bin/pip 2>/dev/null | head -1); PIP=${PIP:-pip}\n\
         dl(){ [ -s \"$2\" ] && return 0; mkdir -p \"$(dirname \"$2\")\"; curl -L --fail --retry 3 -o \"$2.part\" \"$1\" && mv \"$2.part\" \"$2\"; }\n\
         node(){ [ -d \"$N/$2\" ] || git clone --depth 1 \"$1\" \"$N/$2\"; [ -f \"$N/$2/requirements.txt\" ] && $PIP install -q -r \"$N/$2/requirements.txt\"; }\n",
    );
    if include_local_node {
        s.push_str("mkdir -p \"$N/aivs_save_b64\"\ncat > \"$N/aivs_save_b64/__init__.py\" <<'PYEOF'\n");
        s.push_str(LOCAL_NODE);
        s.push_str("\nPYEOF\n");
    }
    let mut seen = std::collections::HashSet::new();
    for m in packs {
        let title: String = m["name"].as_str().unwrap_or("").chars().filter(|c| !c.is_control()).collect();
        s.push_str(&format!("# {title}\n"));
        for n in m["nodes"].as_array().cloned().unwrap_or_default() {
            let (repo, name) = (n["repo"].as_str().unwrap_or(""), n["name"].as_str().unwrap_or(""));
            if !repo.is_empty() && seen.insert(format!("node/{name}")) {
                s.push_str(&format!("node \"{repo}\" \"{name}\"\n"));
            }
        }
        for f in m["files"].as_array().cloned().unwrap_or_default() {
            let url = f["url"].as_str().unwrap_or("");
            let dir = f["dir"].as_str().unwrap_or("");
            let file = url.rsplit('/').next().unwrap_or("");
            if seen.insert(format!("{dir}/{file}")) {
                s.push_str(&format!("dl \"{url}\" \"$M/{dir}/{file}\"\n"));
            }
        }
    }
    s
}

/// One self-contained shell block: the script is gzip+base64 encoded to stay small.
pub fn block(script: &str) -> String {
    let mut gz = GzEncoder::new(Vec::new(), Compression::best());
    gz.write_all(script.as_bytes()).unwrap();
    let b64 = base64::engine::general_purpose::STANDARD.encode(gz.finish().unwrap());
    format!("{BEGIN}\necho '{b64}' | base64 -d | gunzip > /tmp/aivs_install.sh && bash /tmp/aivs_install.sh\n{END}\n")
}

/// Replaces a previous AIVS block (if any) and places the new one before the template's own commands,
/// so models and nodes are on disk before ComfyUI starts.
pub fn patch_onstart(original: &str, block: &str) -> String {
    let mut base = original.to_string();
    if let (Some(a), Some(b)) = (base.find(BEGIN), base.find(END)) {
        if b > a {
            let end = b + END.len();
            base.replace_range(a..end, "");
            base = base.trim_start_matches('\n').to_string();
        }
    }
    if base.starts_with("#!") {
        let nl = base.find('\n').map(|i| i + 1).unwrap_or(base.len());
        let (shebang, rest) = base.split_at(nl);
        format!("{shebang}{block}{rest}")
    } else {
        format!("{block}{base}")
    }
}

pub fn find_hash(v: &Value) -> Option<String> {
    match v {
        Value::Object(m) => {
            if let Some(Value::String(h)) = m.get("hash_id") {
                return Some(h.clone());
            }
            m.values().find_map(find_hash)
        }
        Value::Array(a) => a.iter().find_map(find_hash),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn patch_is_idempotent_and_keeps_shebang() {
        let orig = "#!/bin/bash\necho original\n";
        let once = patch_onstart(orig, &block("echo a"));
        let twice = patch_onstart(&once, &block("echo b"));
        assert!(once.starts_with("#!/bin/bash\n# >>> AIVS BEGIN"));
        assert_eq!(twice.matches("AIVS BEGIN").count(), 1);
        assert!(twice.contains("echo original"));
        assert!(!twice.contains(&block("echo a")));
    }

    #[test]
    fn script_has_models_nodes_and_local_node() {
        let packs = vec![json!({"name":"X","files":[{"dir":"vae","url":"https://h/a/b.safetensors"}],
            "nodes":[{"repo":"https://github.com/o/r","name":"r"}]})];
        let s = build_script(&packs, true);
        assert!(s.contains("AIVSSaveVideoBase64"));
        assert!(s.contains("dl \"https://h/a/b.safetensors\" \"$M/vae/b.safetensors\""));
        assert!(s.contains("node \"https://github.com/o/r\" \"r\""));
    }
}
